"""Lists the Rust crates statically linked into the ipa_rapier native library, with their licence texts.

Writes src/main/resources/natives/ipa_rapier/THIRD-PARTY-LICENSES.txt (shipped in the jar next to LICENSE-RAPIER).
Covers the normal dependencies of ipa_rapier for the six targets build-natives.sh builds; proc-macro crates and their
dependencies (run by the compiler, not linked) and the workspace's own path crates (ipa_rapier, marten, the vendored Rapier fork:
see NOTICE and LICENSE-RAPIER) are left out. Licence texts come from each crate's published sources; identical texts
are printed once. Needs cargo (fetches crate sources into natives/.cargo-cache on first run).

    python3 scripts/native-licenses.py           write the file
    python3 scripts/native-licenses.py --check   fail if the file is out of date
"""
import hashlib
import json
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NATIVES = ROOT / "natives"
OUT = ROOT / "src/main/resources/natives/ipa_rapier/THIRD-PARTY-LICENSES.txt"
PACKAGE = "ipa_rapier"
TARGETS = [
    "x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu",
    "x86_64-apple-darwin", "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc", "aarch64-pc-windows-msvc",
]
LICENCE_PREFIXES = ("license", "licence", "copying", "copyright", "notice", "unlicense")


def cargo(*args):
    env = dict(os.environ, CARGO_HOME=str(NATIVES / ".cargo-cache"))
    return subprocess.run(["cargo", "+stable", *args, "--locked", "--manifest-path", str(NATIVES / "Cargo.toml")],
                          env=env, check=True, capture_output=True, text=True).stdout


def linked_ids(packages):
    ids = set()
    for target in TARGETS:
        tree = cargo("tree", "-p", PACKAGE, "-e", "normal,no-proc-macro", "--target", target, "--prefix", "none", "-f", "{p}")
        for line in tree.splitlines():
            parts = line.replace(" (*)", "").split()
            if len(parts) >= 2:
                ids.add((parts[0], parts[1].lstrip("v")))
    return [p for p in packages if (p["name"], p["version"]) in ids]


def licence_files(package):
    directory = pathlib.Path(package["manifest_path"]).parent
    files = []
    for entry in sorted(directory.iterdir()):
        if entry.is_file() and entry.name.lower().startswith(LICENCE_PREFIXES):
            files.append(entry)
    return files


def render():
    meta = json.loads(cargo("metadata", "--format-version", "1"))
    crates = []
    for package in linked_ids(meta["packages"]):
        if package["source"] is None:  # workspace and vendored path crates
            continue
        if any("proc-macro" in target["kind"] for target in package["targets"]):
            continue
        crates.append(package)
    crates.sort(key=lambda p: (p["name"], p["version"]))

    lines = [
        "Third-party Rust crates statically linked into the ipa_rapier native libraries",
        "",
        "The ipa_rapier libraries in this directory contain, besides the Sable and Rapier code named in",
        "META-INF/NOTICE and LICENSE-RAPIER, the following crates from crates.io under their own licences.",
        "Their licence texts follow the list; each crate's source is available from crates.io at",
        "https://crates.io/crates/<name>/<version>. Generated by scripts/native-licenses.py.",
        "",
    ]
    width = max(len(f"{p['name']} {p['version']}") for p in crates)
    for p in crates:
        lines.append(f"{p['name'] + ' ' + p['version']:<{width}}  {p.get('license') or p.get('license_file') or '?'}")
    lines.append("")

    seen = {}
    for p in crates:
        lines += ["=" * 100, f"{p['name']} {p['version']}", f"Licence: {p.get('license') or '?'}",
                  f"Source: https://crates.io/crates/{p['name']}/{p['version']}"
                  + (f" ({p['repository']})" if p.get("repository") else ""), "=" * 100, ""]
        files = licence_files(p)
        if not files:
            lines += [f"The published crate has no licence file; its manifest declares: {p.get('license')}.", ""]
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            digest = hashlib.sha256(text.encode()).hexdigest()
            if digest in seen:
                lines += [f"--- {f.name}: same text as {seen[digest]} above", ""]
                continue
            seen[digest] = f"{p['name']} {p['version']} {f.name}"
            lines += [f"--- {f.name}", "", text, ""]
    return "\n".join(lines).rstrip() + "\n", len(crates)


def main():
    text, count = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/native-licenses.py")
            sys.exit(1)
        print(f"{OUT.relative_to(ROOT)} is up to date ({count} crates)")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({count} crates, {len(text) // 1024} KiB)")


if __name__ == "__main__":
    main()
